const faqSection = (page, ui) => page.faqs?.length ? `<section id="faqs" class="section faq">
  <div><p class="eyebrow">${ui.faqEyebrow}</p><h2>${ui.faqTitle}</h2></div>
  <div class="faq-list">${page.faqs.map(([q, a]) => `\n    <details><summary>${q}</summary><p>${a}</p></details>`).join('')}
  </div>
</section>` : '';

const articles = () => pages.filter(p => p.kind === 'article');
const articleList = ui => `<div class="article-list">${articles().map(a => `<a class="article-card" href="${href(a.path)}"><strong>${a.title}</strong><span>${a.description}</span><em>${ui.readMore} →</em></a>`).join('')}</div>`;

function toolPage(page) {
  const ui = UI[page.lang || 'en'];
  const schema = [{
    '@context': 'https://schema.org', '@type': 'WebApplication', name: stripTags(page.h1), url: urlFor(page.path), description: page.description,
    applicationCategory: 'UtilitiesApplication', operatingSystem: 'Any', browserRequirements: 'Requires JavaScript', inLanguage: page.lang || 'en', isAccessibleForFree: true,
    offers: { '@type': 'Offer', price: '0', priceCurrency: 'USD' }
  }];
  // The home page tells search engines which image is the site's logo.
  if (page.path === '') schema.push({ '@context': 'https://schema.org', '@type': 'Organization', name: SITE_NAME, url: SITE_URL, logo: urlFor('icon-512.png') });
  if (page.faqs?.length) schema.push({ '@context': 'https://schema.org', '@type': 'FAQPage', mainEntity: page.faqs.map(([q, a]) => ({ '@type': 'Question', name: q, acceptedAnswer: { '@type': 'Answer', text: stripTags(a) } })) });
  return `${head(page, ui, schema)}
<body data-action="${page.action}">
${SPRITE}
${header(page, ui)}
<main id="main">
<section class="hero" aria-labelledby="headline">
  <p class="eyebrow">${page.eyebrow}</p>
  <h1 id="headline">${page.h1}</h1>
  <p class="hero-copy">${page.lead}</p>
</section>
${workspace(page, ui)}
${page.sections}
${faqSection(page, ui)}
${toolGrid(ui, page.path, page.lang === 'hi' ? ui.moreTools : 'More free tools for the same text.')}
${page.path === '' ? `<section class="section"><p class="eyebrow">ARTICLES</p><h2>Understand the score before you trust it.</h2>${articleList(ui)}</section>` : ''}
</main>
${footer(ui)}
</body>
</html>
`;
}

function articlePage(page) {
  const ui = UI.en;
  const schema = [{
    '@context': 'https://schema.org', '@type': 'Article', headline: page.title, description: page.description, datePublished: page.date, dateModified: page.date,
    mainEntityOfPage: urlFor(page.path), image: urlFor('og.png'), author: { '@type': 'Organization', name: SITE_NAME, url: SITE_URL }, publisher: { '@type': 'Organization', name: SITE_NAME, url: SITE_URL }
  }];
  const others = articles().filter(a => a.path !== page.path);
  return `${head(page, ui, schema)}
<body>
${header(page, ui)}
<main id="main" class="legal article">
<p class="eyebrow"><a href="/articles">${ui.backToArticles.toUpperCase()}</a></p>
<h1>${page.h1}</h1>
<p class="article-lead">${page.lead}</p>
<p class="updated">${ui.published} <time datetime="${page.date}">${new Date(page.date + 'T00:00:00Z').toLocaleDateString('en-GB', { day: 'numeric', month: 'long', year: 'numeric', timeZone: 'UTC' })}</time></p>
${page.body}
<p class="article-cta"><a class="button strong" href="/">${ui.tryIt}</a></p>
<h2>More articles</h2>
<ul>${others.map(a => `<li><a href="${href(a.path)}">${a.title}</a></li>`).join('')}</ul>
</main>
${footer(ui)}
</body>
</html>
`;
}

function simplePage(page) {
  const ui = UI.en;
  const body = page.kind === 'index' ? `<p class="article-lead">${page.lead}</p>${articleList(ui)}` : page.body.replaceAll('__REPO__', REPO_URL);
  return `${head(page, ui)}
<body>
${header(page, ui)}
<main id="main" class="legal${page.kind === 'index' ? ' article' : ''}">
<h1>${page.h1}</h1>
${body}
</main>
${page.showTools ? toolGrid(ui, null, 'Free tools on this site.') : ''}
${footer(ui)}
</body>
</html>
`;
}

export const renderPage = page => page.kind === 'tool' ? toolPage(page) : page.kind === 'article' ? articlePage(page) : simplePage(page);

export function sitemap() {
  const entries = pages.filter(p => !p.noindex).map(p => `  <url><loc>${urlFor(p.path)}</loc><lastmod>${p.date || UPDATED}</lastmod><priority>${p.priority || '0.5'}</priority></url>`);
  return `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n${entries.join('\n')}\n</urlset>\n`;
}
export const robots = () => `User-agent: *\nAllow: /\nDisallow: /api/\n\nSitemap: ${urlFor('sitemap.xml')}\n`;

export function headers() {
  const analytics = Boolean(CF_ANALYTICS_TOKEN);
  const csp = [
    "default-src 'self'", `script-src 'self'${analytics ? ' https://static.cloudflareinsights.com' : ''}`, "style-src 'self'", "img-src 'self' data:", "font-src 'self'",
    `connect-src 'self'${analytics ? ' https://cloudflareinsights.com' : ''}`, "worker-src 'self'", "object-src 'none'", "base-uri 'none'", "form-action 'self'", "frame-ancestors 'none'"
  ].join('; ');
  return `/*
  Content-Security-Policy: ${csp}
  X-Content-Type-Options: nosniff
  X-Frame-Options: DENY
  Referrer-Policy: strict-origin-when-cross-origin
  Strict-Transport-Security: max-age=31536000; includeSubDomains
  Permissions-Policy: camera=(), microphone=(), geolocation=()

/fonts/*
  Cache-Control: public, max-age=31536000, immutable

/vendor/*
  Cache-Control: public, max-age=31536000, immutable
`;
}
