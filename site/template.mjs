function head(page, ui, extraSchema = []) {
  const lang = page.lang || 'en';
  const canonical = urlFor(page.path === '404' ? '' : page.path);
  const fullTitle = page.kind === 'tool' && !page.path ? page.title : `${page.title} | ${SITE_NAME}`;
  const alternates = page.path === '' || page.path === 'hi'
    ? `\n<link rel="alternate" hreflang="en" href="${urlFor('')}">\n<link rel="alternate" hreflang="hi" href="${urlFor('hi')}">\n<link rel="alternate" hreflang="x-default" href="${urlFor('')}">` : '';
  return `<!doctype html>
<!-- Generated by scripts/build-pages.mjs from site/content.mjs. Do not edit this file directly. -->
<html lang="${lang}">
<head>
<meta charset="UTF-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<meta name="theme-color" content="#214e3c">
<title>${esc(fullTitle)}</title>
<meta name="description" content="${esc(page.description)}">${page.noindex ? '\n<meta name="robots" content="noindex">' : `\n<link rel="canonical" href="${canonical}">`}${alternates}${GOOGLE_SITE_VERIFICATION && !page.path ? `\n<meta name="google-site-verification" content="${esc(GOOGLE_SITE_VERIFICATION)}">` : ''}
<meta property="og:site_name" content="${SITE_NAME}">
<meta property="og:title" content="${esc(page.title)}">
<meta property="og:description" content="${esc(page.description)}">
<meta property="og:type" content="${page.kind === 'article' ? 'article' : 'website'}">
<meta property="og:url" content="${canonical}">
<meta property="og:image" content="${urlFor('og.png')}">
<meta property="og:image:width" content="1200">
<meta property="og:image:height" content="630">
<meta name="twitter:card" content="summary_large_image">
<link rel="icon" href="/mark.svg" type="image/svg+xml">
<link rel="apple-touch-icon" href="/apple-touch-icon.png">
<link rel="preload" href="/fonts/dm-sans-latin-wght-normal.woff2" as="font" type="font/woff2" crossorigin>
<link rel="stylesheet" href="/styles.css">${page.kind === 'tool' ? '\n<script type="module" src="/app.js"></script>' : ''}${CF_ANALYTICS_TOKEN ? `\n<script defer src="https://static.cloudflareinsights.com/beacon.min.js" data-cf-beacon='{"token": "${esc(CF_ANALYTICS_TOKEN)}"}'></script>` : ''}
${extraSchema.map(jsonLd).join('\n')}
</head>`;
}

function header(page, ui) {
  const current = page.path;
  return `<a class="skip" href="${page.kind === 'tool' ? '#text-input' : '#main'}">${ui.skip}</a>
<header class="header">
  <a class="brand" href="${href(page.lang === 'hi' ? 'hi' : '')}" aria-label="${ui.home}"><img src="/mark.svg" width="34" height="34" alt=""><span>${SITE_NAME}<span class="brand-dot">.</span></span></a>
  <nav aria-label="${ui.mainNav}">${ui.nav.map(([path, label]) => `<a href="${href(path)}"${path === current || (path === 'articles' && current.startsWith('articles/')) ? ' aria-current="page"' : ''}>${label}</a>`).join('')}</nav>
</header>`;
}

